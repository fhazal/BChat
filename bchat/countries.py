def country_of(host: str) -> str:
    h = host.rpartition("@")[2].rstrip(".")
    last = h.rsplit(".", 1)[-1]
    if not h or last.isdigit():
        return "Unknown"
    return DOMAINS.get(last.lower(), "Unknown")
