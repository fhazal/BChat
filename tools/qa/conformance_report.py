"""IRC/IRCv3 conformance status: tools/qa/data/conformance.json + the latest test results -> docs/PROTOCOL-CONFORMANCE.md.

Checks that the table can't drift from the tests: every test it names must exist, and every test in
tests/test_conformance.py must be in it. With --junit (a pytest --junitxml file) each feature gets the real result:
passed, failed, known deviation (strict xfail with a FINDING), or not run.

    python tools/qa/conformance_report.py [--junit results.xml] [--out docs/PROTOCOL-CONFORMANCE.md] [--json result.json]

Exit 1 when the table and the tests disagree, or a listed test failed.
"""
import argparse
import datetime
import json
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "tools" / "qa" / "data" / "conformance.json"


def defined_tests(path: Path) -> set[str]:
    return set(re.findall(r"^def (test_\w+)\(", path.read_text(encoding="utf-8"), re.M))


def junit_results(path: Path) -> dict[str, str]:
    """test id -> passed | failed | xfail | skipped"""
    out = {}
    for case in ET.parse(path).getroot().iter("testcase"):
        tid = case.get("classname", "").replace(".", "/") + ".py::" + case.get("name", "").split("[")[0]
        if case.find("failure") is not None or case.find("error") is not None:
            out[tid] = "failed"
        elif case.find("skipped") is not None:
            sk = case.find("skipped")
            out[tid] = "xfail" if "xfail" in (sk.get("type", "") + sk.get("message", "")).lower() else "skipped"
        else:
            out.setdefault(tid, "passed")
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--junit", action="append", default=[], help="pytest JUnit XML; several are merged")
    ap.add_argument("--out", default=str(ROOT / "docs" / "PROTOCOL-CONFORMANCE.md"))
    ap.add_argument("--json", default="")
    ap.add_argument("--data", default=str(DATA), help="the feature table (default tools/qa/data/conformance.json)")
    a = ap.parse_args()
    data = json.loads(Path(a.data).read_text(encoding="utf-8"))
    feats, findings = data["features"], data.get("findings", {})
    problems = []

    # the table and the tests must agree
    listed = {t for f in feats for t in f["tests"]}
    for t in sorted(listed):
        file, _, name = t.partition("::")
        p = ROOT / file
        if not p.exists() or name not in defined_tests(p):
            problems.append(f"listed but not defined: {t}")
    conf = ROOT / "tests" / "test_conformance.py"
    for name in sorted(defined_tests(conf)):
        if f"tests/test_conformance.py::{name}" not in listed:
            problems.append(f"conformance test not in the table: {name}")

    res, used = {}, []
    for j in a.junit:
        if Path(j).exists():
            res.update(junit_results(Path(j)))
            used.append(Path(j).name)
    rows, failed = [], []
    counts = {"tested": 0, "deviation": 0, "thin": 0, "unsupported": 0, "failing": 0, "not run": 0}
    for f in feats:
        got = [res.get(t, "not run") for t in f["tests"]]
        if f["category"] == "unsupported":
            status, key = "Not supported", "unsupported"
        elif "failed" in got:
            status, key = "**FAILING**", "failing"
            failed += [t for t, g in zip(f["tests"], got) if g == "failed"]
        elif f.get("finding") and "xfail" in got:
            status, key = f"Implemented, **known deviation** ({f['finding']})", "deviation"
        elif f["category"] == "thin":
            status, key = "Implemented, thinly tested", "thin"
        elif res and all(g == "passed" for g in got):
            status, key = f"Implemented, tested ({len(got)} passing)", "tested"
        elif res:
            status, key = "Implemented, tested (some tests not run in this report)", "not run"
        else:
            status, key = "Implemented, tested (no results given)", "not run"
        counts[key] += 1
        tests = ", ".join(f"`{t.split('::')[1]}`" + ("" if not res else f" {'✓' if res.get(t) == 'passed' else '✗' if res.get(t) == 'failed' else '(xfail)' if res.get(t) == 'xfail' else '(not run)'}")
                          for t in f["tests"]) or "—"
        rows.append((f["area"], f["feature"], f["spec"], status, tests + (f" — {f['note']}" if f.get("note") else "")))

    lines = ["# BChat IRC / IRCv3 conformance", "",
             "Generated by `tools/qa/conformance_report.py` from `tools/qa/data/conformance.json`"
             + (f" and the test results in {', '.join(f'`{u}`' for u in used)}" if res else " (no test results given)")
             + f" on {datetime.date.today():%Y-%m-%d}. Do not edit by hand.", "",
             "This lists what BChat implements and what proves it. It is **not** a claim of full IRC or IRCv3",
             "compliance. Tests run against the local simulator `tests/qa_ircd.py` or `tests/fake_ircd.py`.", "",
             f"Summary: {counts['tested']} tested, {counts['deviation']} with a known deviation, {counts['thin']} thinly "
             f"tested, {counts['unsupported']} not supported, {counts['failing']} failing, {counts['not run']} without results.", "",
             "| Area | Feature | Spec | Status | Tests |", "| --- | --- | --- | --- | --- |"]
    lines += [f"| {r[0]} | {r[1]} | {r[2]} | {r[3]} | {r[4]} |" for r in rows]
    if findings:
        lines += ["", "## Findings (deviations kept as strict xfail tests)", ""]
        lines += [f"- **{k}**: {v}" for k, v in findings.items()]
    if problems:
        lines += ["", "## Table problems", ""] + [f"- {p}" for p in problems]
    Path(a.out).write_text("\n".join(lines) + "\n", encoding="utf-8")
    for p in problems:
        print("PROBLEM", p)
    for t in failed:
        print("FAIL", t)
    print(f"--- {counts}  -> {a.out}")
    if a.json:
        Path(a.json).write_text(json.dumps({"ok": counts["tested"] + counts["deviation"] + counts["thin"] + counts["unsupported"],
                                            "fail": len(problems) + len(failed), "skip": counts["not run"],
                                            "failed": problems + failed, "counts": counts}, indent=1), encoding="utf-8")
    return 1 if problems or failed else 0


if __name__ == "__main__":
    sys.exit(main())
